"""Native PostgreSQL archive for the team education engine.

Checkpoint JSON stays TEXT: its exact UTF-8 bytes are covered by the existing
SHA-256 digest.  All writes use the shared deployment fence and transaction.
"""

import hashlib
import json
import secrets
from contextlib import contextmanager
from datetime import UTC, datetime

from education_engine.core.errors import LabError
from education_engine.service.storage import PracticeStore, utc_timestamp
from postgres_backend import PostgresBackendError


class PostgresEducationStore:
    is_postgres = True
    summary = staticmethod(PracticeStore.summary)

    def __init__(self, backend):
        self.backend = backend
        self.lock = backend.lock
        # Never include a connection URL (and its password) in storage metadata.
        self.path = "postgresql:team-education"
        self.practices = backend.table("education", "practices")
        self.events = backend.table("education", "events")
        self.meta = backend.table("education", "meta")
        self.owners = backend.table("education", "owners")
        schemas = {
            "practices": ({key: "text" for key in (
                "id", "mode", "title", "created", "updated", "checkpoint", "digest", "snapshot"
            )}, ("id",)),
            "events": ({"id": "int8", "practice_id": "text", "at": "text", "data": "text"}, ("id",)),
            "meta": ({"key": "text", "value": "text"}, ("key",)),
            "owners": ({"practice_id": "text", "owner_hash": "text"}, ("practice_id",)),
        }
        with self._transaction(write=True) as connection:
            # Inspect every existing table before performing any DDL.  The whole
            # operation also rolls back if an incompatible table is discovered.
            for table, (columns, primary_key) in schemas.items():
                backend.validate_table(
                    connection, "education", table, columns, primary_key=primary_key,
                    identity_columns=("id",) if table == "events" else (),
                )
            connection.execute(f"""CREATE TABLE IF NOT EXISTS {self.practices} (
                id TEXT PRIMARY KEY, mode TEXT NOT NULL, title TEXT NOT NULL,
                created TEXT NOT NULL, updated TEXT NOT NULL,
                checkpoint TEXT NOT NULL, digest TEXT NOT NULL, snapshot TEXT NOT NULL
            )""")
            connection.execute(f"""CREATE TABLE IF NOT EXISTS {self.events} (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                practice_id TEXT NOT NULL, at TEXT NOT NULL, data TEXT NOT NULL
            )""")
            connection.execute(f"""CREATE TABLE IF NOT EXISTS {self.meta} (
                key TEXT PRIMARY KEY, value TEXT NOT NULL
            )""")
            connection.execute(f"""CREATE TABLE IF NOT EXISTS {self.owners} (
                practice_id TEXT PRIMARY KEY, owner_hash TEXT NOT NULL
            )""")
            connection.execute(f'CREATE INDEX IF NOT EXISTS "events_practice" ON {self.events}(practice_id, id)')
            connection.execute(f'CREATE INDEX IF NOT EXISTS "education_owner_lookup" ON {self.owners}(owner_hash)')

    @contextmanager
    def _transaction(self, write=False):
        try:
            with self.backend.transaction(write=write) as connection:
                yield connection
        except LabError:
            raise
        except (PostgresBackendError, OSError):
            if write:
                # SAVE_FAILED is deliberately shared with SQLite: the engine's
                # durable wrappers restore the previous state and pause work.
                raise LabError(
                    "SAVE_FAILED", "저장되지 않았습니다. 실행을 멈췄습니다. 연결 상태를 확인한 뒤 다시 저장하세요.", 503
                ) from None
            raise LabError("READ_FAILED", "저장 기록을 읽을 수 없습니다. 잠시 후 다시 시도하세요.", 503) from None

    @staticmethod
    def _stamp():
        return datetime.now(UTC).isoformat(timespec="microseconds")

    @staticmethod
    def _pagination(limit, offset):
        if (isinstance(offset, bool) or not isinstance(offset, int) or offset < 0
                or limit is not None and (isinstance(limit, bool) or not isinstance(limit, int) or limit < 1)):
            raise LabError("INVALID_PAGINATION", "목록 범위를 확인하세요.", 422)
        return (" OFFSET %s", [offset]) if limit is None else (" LIMIT %s OFFSET %s", [limit, offset])

    @staticmethod
    def filters(mode, q, updated_from, updated_until):
        clauses = ["p.mode=%s", "strpos(lower(p.title), lower(%s)) > 0"]
        values = [mode, q]
        normalized = []
        for bound, operator in ((updated_from, ">="), (updated_until, "<")):
            if bound is None:
                normalized.append(None)
                continue
            stamp = utc_timestamp(bound)
            if stamp is None:
                raise LabError("INVALID_DATE_RANGE", "시간대가 포함된 ISO 날짜를 지정하세요.", 422)
            normalized.append(stamp)
            clauses.append(f"p.updated::timestamptz {operator} %s::timestamptz")
            values.append(stamp)
        if all(stamp is not None for stamp in normalized) and normalized[0] >= normalized[1]:
            raise LabError("INVALID_DATE_RANGE", "시작 시각은 종료 시각보다 빨라야 합니다.", 422)
        return " AND ".join(clauses), values

    @classmethod
    def _items(cls, rows):
        result = []
        for row in rows:
            item = dict(row)
            item["summary"] = cls.summary(item.pop("snapshot"))
            result.append(item)
        return result

    def save(self, practice_id, mode, checkpoint, snapshot, events):
        payload = json.dumps(checkpoint, ensure_ascii=False)
        digest = hashlib.sha256(payload.encode()).hexdigest()
        stamp = self._stamp()
        event_rows = [(practice_id, utc_timestamp(event.get("at")) or stamp,
                       json.dumps(event, ensure_ascii=False)) for event in events]
        with self._transaction(write=True) as connection:
            connection.execute(f"""INSERT INTO {self.practices}
                (id,mode,title,created,updated,checkpoint,digest,snapshot)
                VALUES (%s,%s,%s,%s,%s,%s,%s,%s)
                ON CONFLICT(id) DO UPDATE SET updated=excluded.updated,
                checkpoint=excluded.checkpoint, digest=excluded.digest, snapshot=excluded.snapshot""",
                (practice_id, mode, "개인 실습" if mode == "personal" else "공동 수업",
                 stamp, stamp, payload, digest, json.dumps(snapshot, ensure_ascii=False)))
            if event_rows:
                with connection.cursor() as cursor:
                    cursor.executemany(
                        f"INSERT INTO {self.events}(practice_id,at,data) VALUES (%s,%s,%s)", event_rows)
        return stamp

    def list(self, mode, q="", limit=None, offset=0, updated_from=None, updated_until=None):
        where, values = self.filters(mode, q, updated_from, updated_until)
        pagination, page_values = self._pagination(limit, offset)
        with self._transaction() as connection:
            rows = connection.execute(
                f"SELECT p.id,p.mode,p.title,p.created,p.updated,p.snapshot FROM {self.practices} p "
                f"WHERE {where} ORDER BY p.updated::timestamptz DESC,p.id" + pagination,
                values + page_values,
            ).fetchall()
            return self._items(rows)

    def count(self, mode, q="", updated_from=None, updated_until=None):
        where, values = self.filters(mode, q, updated_from, updated_until)
        with self._transaction() as connection:
            return connection.execute(
                f"SELECT count(*) AS total FROM {self.practices} p WHERE {where}", values
            ).fetchone()["total"]

    def _read(self, connection, practice_id, mode):
        row = connection.execute(
            f"SELECT * FROM {self.practices} WHERE id=%s AND mode=%s", (practice_id, mode)
        ).fetchone()
        if row is None:
            raise LabError("PRACTICE_NOT_FOUND", "저장된 실습을 찾을 수 없습니다.", 404)
        item = dict(row)
        try:
            if hashlib.sha256(item["checkpoint"].encode()).hexdigest() != item["digest"]:
                raise ValueError("checkpoint digest")
            item["checkpoint"] = json.loads(item["checkpoint"])
            item["snapshot"] = json.loads(item["snapshot"])
            item["events"] = [
                {**json.loads(event["data"]), "id": event["id"], "at": event["at"]}
                for event in connection.execute(
                    f"SELECT id,at,data FROM {self.events} WHERE practice_id=%s ORDER BY id", (practice_id,)
                ).fetchall()
            ]
        except (ValueError, TypeError, AttributeError):
            raise LabError("CHECKPOINT_INVALID", "저장 데이터가 손상됐습니다. 원본은 변경하지 않았습니다.", 409) from None
        return item

    def read(self, practice_id, mode):
        with self._transaction() as connection:
            return self._read(connection, practice_id, mode)

    def rename(self, practice_id, mode, title):
        with self._transaction(write=True) as connection:
            self._read(connection, practice_id, mode)
            connection.execute(f"UPDATE {self.practices} SET title=%s WHERE id=%s AND mode=%s", (title, practice_id, mode))

    def delete(self, practice_id, mode):
        with self._transaction(write=True) as connection:
            self._read(connection, practice_id, mode)
            connection.execute(f"DELETE FROM {self.events} WHERE practice_id=%s", (practice_id,))
            connection.execute(f"DELETE FROM {self.owners} WHERE practice_id=%s", (practice_id,))
            connection.execute(f"DELETE FROM {self.practices} WHERE id=%s AND mode=%s", (practice_id, mode))

    def owner_secret(self):
        with self._transaction(write=True) as connection:
            connection.execute(
                f"INSERT INTO {self.meta}(key,value) VALUES (%s,%s) ON CONFLICT(key) DO NOTHING",
                ("owner_cookie_secret", secrets.token_hex(32)),
            )
            row = connection.execute(
                f"SELECT value FROM {self.meta} WHERE key=%s", ("owner_cookie_secret",)
            ).fetchone()
            try:
                secret = bytes.fromhex(row["value"])
                if len(secret) != 32:
                    raise ValueError("owner secret length")
            except (ValueError, TypeError, KeyError):
                raise LabError("SAVE_FAILED", "실습 소유권 설정을 읽을 수 없습니다.", 503) from None
            return secret

    def owner_assign(self, practice_id, owner_hash):
        with self._transaction(write=True) as connection:
            exists = connection.execute(
                f"SELECT 1 FROM {self.practices} WHERE id=%s AND mode='personal'", (practice_id,)
            ).fetchone()
            if not exists:
                raise LabError("PRACTICE_NOT_FOUND", "저장된 실습을 찾을 수 없습니다.", 404)
            connection.execute(
                f"INSERT INTO {self.owners}(practice_id,owner_hash) VALUES (%s,%s) "
                "ON CONFLICT(practice_id) DO NOTHING", (practice_id, owner_hash),
            )
            row = connection.execute(
                f"SELECT owner_hash FROM {self.owners} WHERE practice_id=%s", (practice_id,)
            ).fetchone()
            if row["owner_hash"] != owner_hash:
                raise LabError("OWNERSHIP_CONFLICT", "다른 브라우저의 실습입니다.", 409)

    def owner_owns(self, practice_id, owner_hash):
        with self._transaction() as connection:
            return connection.execute(
                f"SELECT 1 FROM {self.owners} o JOIN {self.practices} p ON p.id=o.practice_id "
                "WHERE o.practice_id=%s AND o.owner_hash=%s AND p.mode='personal'", (practice_id, owner_hash)
            ).fetchone() is not None

    def owner_remove(self, practice_id):
        with self._transaction(write=True) as connection:
            connection.execute(f"DELETE FROM {self.owners} WHERE practice_id=%s", (practice_id,))

    def owner_list(self, owner_hash, query):
        where, values = self.filters("personal", query.q.strip(), query.updatedFrom, query.updatedUntil)
        pagination, page_values = self._pagination(query.limit, query.offset)
        source = f"FROM {self.practices} p JOIN {self.owners} o ON p.id=o.practice_id "
        condition = f"WHERE {where} AND o.owner_hash=%s"
        with self._transaction() as connection:
            total = connection.execute(
                "SELECT count(*) AS total " + source + condition, values + [owner_hash]
            ).fetchone()["total"]
            rows = connection.execute(
                "SELECT p.id,p.mode,p.title,p.created,p.updated,p.snapshot " + source + condition
                + " ORDER BY p.updated::timestamptz DESC,p.id" + pagination,
                values + [owner_hash] + page_values,
            ).fetchall()
            return {"practices": self._items(rows), "total": total}

    def owner_count(self, owner_hash):
        with self._transaction() as connection:
            return connection.execute(
                f"SELECT count(*) AS total FROM {self.owners} o JOIN {self.practices} p ON p.id=o.practice_id "
                "WHERE o.owner_hash=%s AND p.mode='personal'", (owner_hash,)
            ).fetchone()["total"]

    def total_count(self):
        with self._transaction() as connection:
            return connection.execute(f"SELECT count(*) AS total FROM {self.practices}").fetchone()["total"]

    def event_count(self, practice_id):
        with self._transaction() as connection:
            return connection.execute(
                f"SELECT count(*) AS total FROM {self.events} WHERE practice_id=%s", (practice_id,)
            ).fetchone()["total"]

    def backup(self, destination):
        raise LabError("BACKUP_UNSUPPORTED", "공유 PostgreSQL 기록은 호스팅 서비스에서 백업하세요.", 409)

    def restore_backup(self, source):
        raise LabError("BACKUP_UNSUPPORTED", "공유 PostgreSQL에는 SQLite 백업을 복원할 수 없습니다.", 409)

    def close(self):
        self.backend.close()
